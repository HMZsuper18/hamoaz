using System;
using System.IO;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.InputSystem;
using UnityEngine.InputSystem.UI;
using UnityEngine.Rendering;
using UnityEngine.UI;
using TMPro;

/// <summary>
/// Builds Assets/Scenes/About.unity: the shared cinematic ocean backdrop plus a
/// flush-left about card — game pitch, credits (Development: Hamzah, 3D Design:
/// Moaz), feature list, GitHub repo link, and a Back button to the main menu.
/// Run via Tools/Build About Scene (idempotent; rebuilds the canvas in place).
/// </summary>
public static class AboutUIBuilder
{
    const string ScenePath = "Assets/Scenes/About.unity";
    const string RepoUrl = "https://github.com/HMZsuper18/hamoaz";
    const string PrefabPath = "Assets/Prefabs/MainMenuButton.prefab";
    // Painted brush panel + rim (same torn-edge language as the menu buttons;
    // generated by Tools/IconGenerator/generate_icons.py, keep size in sync
    // with CardWidth below).
    const string BrushCardPath = "Assets/UI/BrushCard.png";
    const string BrushCardOutlinePath = "Assets/UI/BrushCardOutline.png";

    const float CardWidth = 980f;
    const float CardPadX = 56f;

    static TMP_FontAsset s_bodyFont;

    [MenuItem("Tools/Build About Scene")]
    public static void Build()
    {
        try { BuildInternal(); }
        catch (Exception e)
        {
            Debug.LogException(e);
            Debug.LogError("[AboutUI] Build FAILED - see exception above.");
        }
    }

    static void BuildInternal()
    {
        var titleFont = MainMenuUIBuilder.LoadTitleFont();
        var bodyFont = LoadBodyFont();
        Debug.Log("[AboutUI] fonts: title=" + (titleFont != null ? titleFont.name : "fallback")
                  + " body=" + (bodyFont != null ? bodyFont.name : "fallback"));

        var prefab = AssetDatabase.LoadAssetAtPath<GameObject>(PrefabPath);
        if (prefab == null)
            throw new Exception("MainMenuButton prefab missing - run Tools/Build Main Menu Buttons first.");

        var iconCode = LoadSprite("Assets/UI/Icons/IconCode.png");
        var iconBack = LoadSprite("Assets/UI/Icons/IconBack.png");
        var brushCard = LoadSprite(BrushCardPath);
        var brushCardOutline = LoadSprite(BrushCardOutlinePath);
        AssetDatabase.SaveAssets();

        OpenOrCreateScene();
        BuildBackdrop();
        BuildCanvas(prefab, titleFont, bodyFont, iconCode, iconBack, brushCard, brushCardOutline);

        EnsureInBuildSettings("Assets/Scenes/MainMenu.unity");
        EnsureInBuildSettings(ScenePath);

        var scene = UnityEngine.SceneManagement.SceneManager.GetActiveScene();
        if (scene.IsValid() && scene.isLoaded)
        {
            EditorSceneManager.MarkSceneDirty(scene);
            EditorSceneManager.SaveScene(scene);
        }
        AssetDatabase.SaveAssets();
        Debug.Log("[AboutUI] About scene built (backdrop + about card + Back/Repo buttons). Scene saved: " + ScenePath);
    }

    // ---------- scene + backdrop ----------

    static void OpenOrCreateScene()
    {
        if (File.Exists(ScenePath))
        {
            EditorSceneManager.OpenScene(ScenePath, OpenSceneMode.Single);
        }
        else
        {
            var scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
            EditorSceneManager.SaveScene(scene, ScenePath);
        }
    }

    // The cinematic-look builder configures Camera.main / "Directional Light" /
    // the sea, but assumes they exist (the main-menu template scene ships with
    // them). A fresh About scene is empty, so create the bare minimum first.
    static void BuildBackdrop()
    {
        if (Camera.main == null)
        {
            var camGo = new GameObject("Main Camera");
            camGo.tag = "MainCamera";
            camGo.AddComponent<Camera>();
            camGo.AddComponent<AudioListener>();
        }
        if (GameObject.Find("Directional Light") == null)
        {
            var sunGo = new GameObject("Directional Light");
            sunGo.AddComponent<Light>().type = LightType.Directional;
        }
        if (GameObject.Find("Global Volume") == null)
        {
            var volGo = new GameObject("Global Volume");
            var vol = volGo.AddComponent<Volume>();
            vol.isGlobal = true;
            vol.sharedProfile = AssetDatabase.LoadAssetAtPath<VolumeProfile>("Assets/Settings/SampleSceneProfile.asset");
        }

        // Same sea/sky/fog/sun/post-processing as the main menu so navigation
        // between the two scenes is seamless.
        ApplyCinematicMenuLook.ApplyToActiveScene();
    }

    // ---------- canvas ----------

    static void BuildCanvas(GameObject prefab, TMP_FontAsset titleFont, TMP_FontAsset bodyFont, Sprite iconCode, Sprite iconBack, Sprite brushCard, Sprite brushCardOutline)
    {
        var existing = GameObject.Find("AboutCanvas");
        if (existing != null) UnityEngine.Object.DestroyImmediate(existing);

        var canvasGo = new GameObject("AboutCanvas");
        var canvas = canvasGo.AddComponent<Canvas>();
        canvas.renderMode = RenderMode.ScreenSpaceOverlay;
        canvasGo.AddComponent<GraphicRaycaster>();
        var scaler = canvasGo.AddComponent<CanvasScaler>();
        scaler.uiScaleMode = CanvasScaler.ScaleMode.ScaleWithScreenSize;
        scaler.referenceResolution = new Vector2(1920f, 1080f);
        scaler.screenMatchMode = CanvasScaler.ScreenMatchMode.Expand;

        var safeGo = new GameObject("SafeArea");
        var safeRt = safeGo.AddComponent<RectTransform>();
        safeRt.SetParent(canvasGo.transform, false);
        safeRt.anchorMin = Vector2.zero;
        safeRt.anchorMax = Vector2.one;
        safeRt.offsetMin = Vector2.zero;
        safeRt.offsetMax = Vector2.zero;
        safeGo.AddComponent<SafeAreaFitter>();

        var panelGo = new GameObject("AboutPanel");
        var panelRt = panelGo.AddComponent<RectTransform>();
        panelRt.SetParent(safeGo.transform, false);
        // Contain-fit (not FlushLeftHeightScale): the card is much wider than the
        // main menu's 372px buttons, so it must scale to fit BOTH axes or it gets
        // cut off on narrow screens (4:3, portrait, small windows).
        var fit = panelGo.AddComponent<ContainFitScale>();
        fit.leftMargin = 96f;
        fit.margin = 72f;
        fit.minScale = 0.45f;
        fit.maxScale = 1.3f;
        var vlg = panelGo.AddComponent<VerticalLayoutGroup>();
        vlg.padding = new RectOffset(0, 0, 0, 0);
        vlg.spacing = 18f;
        vlg.childAlignment = TextAnchor.UpperLeft;
        vlg.childControlWidth = true;
        vlg.childControlHeight = true;
        vlg.childForceExpandWidth = false;
        vlg.childForceExpandHeight = false;
        var csf = panelGo.AddComponent<ContentSizeFitter>();
        csf.horizontalFit = ContentSizeFitter.FitMode.PreferredSize;
        csf.verticalFit = ContentSizeFitter.FitMode.PreferredSize;

        BuildCard(panelRt, titleFont, bodyFont, brushCard, brushCardOutline);
        BuildButtons(panelRt, prefab, iconCode, iconBack);

        if (GameObject.Find("EventSystem") == null)
        {
            var es = new GameObject("EventSystem");
            es.AddComponent<EventSystem>();
            var module = es.AddComponent<InputSystemUIInputModule>();
            var actions = AssetDatabase.LoadAssetAtPath<InputActionAsset>("Assets/InputSystem_Actions.inputactions");
            if (actions != null) module.actionsAsset = actions;
        }
    }

    static void BuildCard(RectTransform panelRt, TMP_FontAsset titleFont, TMP_FontAsset bodyFont,
        Sprite brushCard, Sprite brushCardOutline)
    {
        // Painted brush panel (torn-edge language of the menu buttons - same
        // body #375F73 / rim #4E7185 pairing as the secondary button). Color
        // pre-compensated for ACES + vignette, same convention as the menu
        // buttons (palette ocean-panel #19465A).
        var cardGo = new GameObject("Card");
        cardGo.transform.SetParent(panelRt, false);
        var cardImg = cardGo.AddComponent<Image>();
        if (brushCard != null)
        {
            cardImg.sprite = brushCard;
            cardImg.type = Image.Type.Simple;
        }
        cardImg.color = MainMenuUIBuilder.Hex("#375F73");
        cardImg.color = new Color(cardImg.color.r, cardImg.color.g, cardImg.color.b, 0.90f);

        // Light rim tracing the torn shape, above the body but below content
        // (same layering as BuildTemplate's Outline on the menu buttons).
        if (brushCardOutline != null)
        {
            var outlineGo = new GameObject("Outline", typeof(RectTransform));
            outlineGo.transform.SetParent(cardGo.transform, false);
            var outlineRt = outlineGo.GetComponent<RectTransform>();
            outlineRt.anchorMin = Vector2.zero;
            outlineRt.anchorMax = Vector2.one;
            outlineRt.offsetMin = Vector2.zero;
            outlineRt.offsetMax = Vector2.zero;
            var outlineImg = outlineGo.AddComponent<Image>();
            outlineImg.sprite = brushCardOutline;
            outlineImg.type = Image.Type.Simple;
            outlineImg.color = MainMenuUIBuilder.Hex("#4E7185");
            outlineImg.raycastTarget = false;
            outlineGo.AddComponent<LayoutElement>().ignoreLayout = true;
        }
        var cardLe = cardGo.AddComponent<LayoutElement>();
        cardLe.minWidth = CardWidth;
        cardLe.preferredWidth = CardWidth;
        cardLe.maxWidth = CardWidth;
        var cardVlg = cardGo.AddComponent<VerticalLayoutGroup>();
        cardVlg.padding = new RectOffset((int)CardPadX, (int)CardPadX, 44, 44);
        cardVlg.spacing = 14f;
        cardVlg.childAlignment = TextAnchor.UpperLeft;
        cardVlg.childControlWidth = true;
        cardVlg.childControlHeight = true;
        // No force-expand: it would stretch the fixed-width menu buttons (their
        // root HLG reports flexible width). Texts get an explicit preferred
        // width instead, which is what TMP wraps against.
        cardVlg.childForceExpandWidth = false;
        cardVlg.childForceExpandHeight = false;
        var cardCsf = cardGo.AddComponent<ContentSizeFitter>();
        cardCsf.horizontalFit = ContentSizeFitter.FitMode.PreferredSize;
        cardCsf.verticalFit = ContentSizeFitter.FitMode.PreferredSize;

        float textWidth = CardWidth - CardPadX * 2f;

        // Palette lagoon accent (pre-compensated, same teal as the menu buttons).
        var accent = CreateRectImage("AccentBar", cardGo.transform, MainMenuUIBuilder.Hex("#22B8D3"));
        var accentLe = accent.gameObject.AddComponent<LayoutElement>();
        accentLe.preferredWidth = 120f;
        accentLe.preferredHeight = 6f;
        accentLe.flexibleWidth = 0f;

        var title = CreateText("Title", cardGo.transform, "hamoaz", titleFont, 64f,
            MainMenuUIBuilder.Hex("#FFD97A"), textWidth); // pre-comp palette gold #F5C451
        title.fontStyle = FontStyles.Normal;

        CreateText("Tagline", cardGo.transform,
            "Low-poly ocean survival · open source",
            bodyFont, 28f, SecondaryText(), textWidth);

        CreateText("Description", cardGo.transform,
            "Build your raft, scavenge floating debris, and ride the open waves — " +
            "a low-poly 3D survival game inspired by Raft. Fully open source, built " +
            "for Android, with local Wi-Fi multiplayer.",
            bodyFont, 24f, SecondaryText(), textWidth);

        var divider = CreateRectImage("Divider", cardGo.transform, MainMenuUIBuilder.Hex("#22B8D3"));
        divider.color = new Color(divider.color.r, divider.color.g, divider.color.b, 0.35f);
        var divLe = divider.gameObject.AddComponent<LayoutElement>();
        divLe.preferredWidth = textWidth;
        divLe.preferredHeight = 2f;

        CreateText("CreditsHeader", cardGo.transform, "CREDITS",
            bodyFont, 20f, MainMenuUIBuilder.Hex("#22B8D3"), textWidth);

        CreateText("CreditDevelopment", cardGo.transform,
            "<color=#C3D6DE>Development</color> — <color=#FFFFFF>Hamzah</color>",
            bodyFont, 26f, Color.white, textWidth);
        CreateText("Credit3D", cardGo.transform,
            "<color=#C3D6DE>3D Design</color> — <color=#FFFFFF>Moaz</color>",
            bodyFont, 26f, Color.white, textWidth);

        CreateText("Features", cardGo.transform,
            "Open source · Android · Local Wi-Fi multiplayer",
            bodyFont, 24f, MainMenuUIBuilder.Hex("#FFD97A"), textWidth);

        var spacer = new GameObject("Spacer", typeof(RectTransform));
        spacer.transform.SetParent(cardGo.transform, false);
        spacer.AddComponent<LayoutElement>().minHeight = 10f;
    }

    static void BuildButtons(RectTransform panelRt, GameObject prefab, Sprite iconCode, Sprite iconBack)
    {
        // Repo button (primary teal) - opens the GitHub repository in the browser.
        var repoGo = (GameObject)PrefabUtility.InstantiatePrefab(prefab, panelRt.transform);
        repoGo.name = "RepoButton";
        PinButton(repoGo);
        MainMenuUIBuilder.ConfigureButton(repoGo, "View on GitHub", iconCode, true);
        var repoNav = repoGo.AddComponent<SceneButton>();
        repoNav.url = RepoUrl;

        // Back button (secondary) - returns to the main menu.
        var backGo = (GameObject)PrefabUtility.InstantiatePrefab(prefab, panelRt.transform);
        backGo.name = "BackButton";
        PinButton(backGo);
        MainMenuUIBuilder.ConfigureButton(backGo, "Back", iconBack, false);
        var backNav = backGo.AddComponent<SceneButton>();
        backNav.sceneName = "MainMenu";
    }

    static void PinButton(GameObject go)
    {
        var le = go.AddComponent<LayoutElement>();
        le.minWidth = 372f; le.preferredWidth = 372f; le.maxWidth = 372f;
        le.minHeight = 68f; le.preferredHeight = 68f; le.maxHeight = 68f;
        // Explicit 0 (not the -1 default): a VerticalLayoutGroup sizes children
        // with flexible > 0 to the full container width, and the inner HLG of
        // the button prefab reports flexibleWidth = 1 (its label). -1 would be
        // ignored by LayoutUtility and the buttons would stretch to card width.
        le.flexibleWidth = 0f;
        le.flexibleHeight = 0f;
    }

    // ---------- helpers ----------

    static TextMeshProUGUI CreateText(string name, Transform parent, string text,
        TMP_FontAsset font, float size, Color color, float wrapWidth)
    {
        var go = new GameObject(name);
        go.transform.SetParent(parent, false);
        var tmp = go.AddComponent<TextMeshProUGUI>();
        tmp.text = text;
        if (font != null) tmp.font = font;
        tmp.fontSize = size;
        tmp.color = color;
        tmp.alignment = TextAlignmentOptions.TopLeft;
        tmp.textWrappingMode = TextWrappingModes.Normal;
        tmp.overflowMode = TextOverflowModes.Overflow;
        tmp.raycastTarget = false;
        var le = go.AddComponent<LayoutElement>();
        le.preferredWidth = wrapWidth;
        le.flexibleWidth = 0f;
        return tmp;
    }

    static Image CreateRectImage(string name, Transform parent, Color color)
    {
        var go = new GameObject(name, typeof(RectTransform));
        go.transform.SetParent(parent, false);
        var img = go.AddComponent<Image>();
        img.color = color;
        img.raycastTarget = false;
        return img;
    }

    // Pre-compensated palette text color (palette secondary #AFC4CE) — matches the
    // menu-button convention of tuning source colors through ACES + vignette.
    static Color SecondaryText() => MainMenuUIBuilder.Hex("#C3D6DE");

    static TMP_FontAsset LoadBodyFont()
    {
        if (s_bodyFont != null) return s_bodyFont;
        const string ttf = "Assets/UI/Fonts/Inter-SemiBold.ttf";
        const string asset = "Assets/UI/Fonts/Inter-SemiBold SDF.asset";
        try
        {
            s_bodyFont = AssetDatabase.LoadAssetAtPath<TMP_FontAsset>(asset);
            if (s_bodyFont != null) return s_bodyFont;
            if (!File.Exists(ttf)) return null;
            var font = AssetDatabase.LoadAssetAtPath<Font>(ttf);
            if (font == null)
            {
                AssetDatabase.ImportAsset(ttf, ImportAssetOptions.ForceUpdate);
                font = AssetDatabase.LoadAssetAtPath<Font>(ttf);
            }
            if (font == null) return null;
            var fa = TMP_FontAsset.CreateFontAsset(font, 64, 8,
                UnityEngine.TextCore.LowLevel.GlyphRenderMode.SDF, 1024, 1024,
                AtlasPopulationMode.Dynamic, true);
            if (fa == null) return null;
            AssetDatabase.CreateAsset(fa, asset);
            if (fa.material != null) AssetDatabase.AddObjectToAsset(fa.material, fa);
            if (fa.atlasTexture != null) AssetDatabase.AddObjectToAsset(fa.atlasTexture, fa);
            EditorUtility.SetDirty(fa);
            AssetDatabase.SaveAssets();
            s_bodyFont = fa;
            return fa;
        }
        catch (Exception e)
        {
            Debug.LogWarning("[AboutUI] Inter TMP asset failed: " + e.Message);
            return null;
        }
    }

    static void EnsureInBuildSettings(string path)
    {
        var scenes = EditorBuildSettings.scenes;
        for (int i = 0; i < scenes.Length; i++)
            if (scenes[i].path == path) return;
        var list = new EditorBuildSettingsScene[scenes.Length + 1];
        scenes.CopyTo(list, 0);
        list[scenes.Length] = new EditorBuildSettingsScene(path, true);
        EditorBuildSettings.scenes = list;
        Debug.Log("[AboutUI] Registered in Build Settings: " + path);
    }

    static Sprite LoadSprite(string path, float? sliceBorder = null)
    {
        AssetDatabase.ImportAsset(path, ImportAssetOptions.ForceUpdate);
        var imp = (TextureImporter)AssetImporter.GetAtPath(path);
        if (imp == null) throw new Exception("No TextureImporter for " + path + " - file missing or failed to import.");
        imp.textureType = TextureImporterType.Sprite;
        imp.spriteImportMode = SpriteImportMode.Single;
        imp.spritePixelsPerUnit = 100f;
        imp.filterMode = FilterMode.Bilinear;
        imp.mipmapEnabled = false;
        imp.textureCompression = TextureImporterCompression.Uncompressed;
        imp.alphaIsTransparency = true;
        if (sliceBorder.HasValue)
            imp.spriteBorder = new Vector4(sliceBorder.Value, sliceBorder.Value, sliceBorder.Value, sliceBorder.Value);
        imp.SaveAndReimport();
        return AssetDatabase.LoadAssetAtPath<Sprite>(path);
    }
}
